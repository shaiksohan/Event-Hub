/*
# Add protected Refer & Earn rewards

## Summary
Adds durable referral codes and coin balances to profiles, plus a single-use referral reward ledger. A new account may use another member's referral code during registration; the referring member receives exactly 10 coins once for that signup.

## New columns
- `profiles.referral_code` — unique shareable code generated by the database for every profile.
- `profiles.referral_coins` — protected reward balance, starting at zero.

## New tables
- `referral_rewards` — records each successful referral exactly once.
  - `id` — unique reward record identifier.
  - `sender_id` — member who owns the referral code.
  - `referred_user_id` — member whose signup triggered the reward.
  - `coins` — reward amount, fixed by the server-side function.
  - `created_at` — reward creation time.

## Security
- Row-level security is enabled on `referral_rewards`.
- Members may read only rewards where they are the sender or referred member.
- Direct writes to the reward ledger are denied; the server-side function performs the atomic claim.
- Referral coin balances are not client-writable through profile updates.
- `claim_referral` derives the referred member from `auth.uid()`, validates the code, prevents self-referrals, and uses a unique referred-user constraint to prevent duplicate rewards.

## Important notes
1. Existing profiles receive a generated code and a zero coin balance without losing existing data.
2. The frontend should call `claim_referral` only after the new profile is created.
3. The function returns the awarded coin count, or zero when the code is invalid or already used.
*/

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS referral_code text,
  ADD COLUMN IF NOT EXISTS referral_coins integer NOT NULL DEFAULT 0;

UPDATE public.profiles
SET referral_code = 'LV' || upper(substr(replace(id::text, '-', ''), 1, 7))
WHERE referral_code IS NULL OR btrim(referral_code) = '';

CREATE UNIQUE INDEX IF NOT EXISTS profiles_referral_code_key
  ON public.profiles (referral_code);

CREATE TABLE IF NOT EXISTS public.referral_rewards (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sender_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  referred_user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  coins integer NOT NULL DEFAULT 10 CHECK (coins = 10),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT referral_rewards_one_signup UNIQUE (referred_user_id)
);

ALTER TABLE public.referral_rewards ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Members can view their referral rewards" ON public.referral_rewards;
CREATE POLICY "Members can view their referral rewards"
ON public.referral_rewards FOR SELECT
TO authenticated
USING (sender_id = auth.uid() OR referred_user_id = auth.uid());

DROP POLICY IF EXISTS "Referral rewards cannot be inserted directly" ON public.referral_rewards;
CREATE POLICY "Referral rewards cannot be inserted directly"
ON public.referral_rewards FOR INSERT
TO authenticated
WITH CHECK (false);

DROP POLICY IF EXISTS "Referral rewards cannot be changed" ON public.referral_rewards;
CREATE POLICY "Referral rewards cannot be changed"
ON public.referral_rewards FOR UPDATE
TO authenticated
USING (false)
WITH CHECK (false);

DROP POLICY IF EXISTS "Referral rewards cannot be deleted" ON public.referral_rewards;
CREATE POLICY "Referral rewards cannot be deleted"
ON public.referral_rewards FOR DELETE
TO authenticated
USING (false);

REVOKE INSERT, UPDATE, DELETE ON public.referral_rewards FROM anon, authenticated;
GRANT SELECT ON public.referral_rewards TO authenticated;

REVOKE UPDATE ON public.profiles FROM authenticated;
GRANT UPDATE (
  full_name,
  bio,
  avatar_url,
  phone,
  location,
  website,
  business_name,
  service_type,
  gender,
  date_of_birth,
  languages
) ON public.profiles TO authenticated;

CREATE OR REPLACE FUNCTION public.claim_referral(p_referral_code text)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  sender uuid;
  claimed integer;
BEGIN
  IF auth.uid() IS NULL OR p_referral_code IS NULL OR btrim(p_referral_code) = '' THEN
    RETURN 0;
  END IF;

  SELECT id INTO sender
  FROM public.profiles
  WHERE referral_code = upper(btrim(p_referral_code))
    AND id <> auth.uid();

  IF sender IS NULL THEN
    RETURN 0;
  END IF;

  INSERT INTO public.referral_rewards (sender_id, referred_user_id, coins)
  VALUES (sender, auth.uid(), 10)
  ON CONFLICT (referred_user_id) DO NOTHING;

  GET DIAGNOSTICS claimed = ROW_COUNT;

  IF claimed = 1 THEN
    UPDATE public.profiles
    SET referral_coins = referral_coins + 10
    WHERE id = sender;
    RETURN 10;
  END IF;

  RETURN 0;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.claim_referral(text) FROM anon;
GRANT EXECUTE ON FUNCTION public.claim_referral(text) TO authenticated;
